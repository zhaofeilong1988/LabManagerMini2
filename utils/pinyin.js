function addCharsAll(groups) {
  Object.keys(groups).forEach((letter) => {
    if (/^[a-z]$/.test(letter)) addChars(letter, groups[letter])
  })
}


// 是否 CJK 汉字（含扩展 A/B 与兼容区）
function isHanChar(code) {
  return (code >= 0x3400 && code <= 0x4dbf) ||
    (code >= 0x4e00 && code <= 0x9fff) ||
    (code >= 0xf900 && code <= 0xfaff)
}

/**
 * 取字符串的「首字母串」：
 *  - 汉字 → 拼音首字母（小写）；表外汉字 → 通配符 '*'
 *  - 字母/数字 → 原样保留（字母统一小写）
 *  - 空格、标点等其它字符忽略
 * 例：getInitials('分子影像实验室')   -> 'fzyxsys'
 *     getInitials('生物成像与分析')    -> 'swcxfxy'
 *     getInitials('后勤保障部')        -> 'hqbzb'（若“勤/障”未收录则为 'h*b*b'）
 */
function getInitials(text) {
  const s = String(text == null ? '' : text)
  let out = ''
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]
    const code = ch.charCodeAt(0)
    if (code >= 65 && code <= 90) { out += String.fromCharCode(code + 32); continue } // A-Z
    if (code >= 97 && code <= 122) { out += ch; continue }                            // a-z
    if (code >= 48 && code <= 57) { out += ch; continue }                             // 0-9
    if (isHanChar(code)) out += (CHAR_MAP[ch] || UNKNOWN)
  }
  return out
}

// 分词连接符：空格、常见标点，以及「与/和/及/暨/的」等组合词连接字
const SEG_SPLIT = /[\s,，、;；:：/／\\|\-—_·()（）\[\]【】]+/
const JOINERS = /[与和及暨的]/g

/**
 * 取字符串的「分词首字母」数组：便于按词搜索（如“分析” -> fx，命中“…与分析实验室”）
 * 例：getPinyinKeys('生物成像与分析实验室') -> ['swcxfxsys', 'swcx', 'fxsys']
 */
function getPinyinKeys(text) {
  const s = String(text == null ? '' : text)
  const keys = []
  const push = (v) => { if (v && keys.indexOf(v) < 0) keys.push(v) }
  push(getInitials(s))
  s.replace(JOINERS, ' ').split(SEG_SPLIT).forEach((seg) => push(getInitials(seg)))
  return keys
}

// 纯子序列匹配（允许跳字），不做通配符处理
// 例：isSubsequence('sxsys', 'swcxfxsys') -> true
function isSubsequence(needle, hay) {
  const n = String(needle == null ? '' : needle)
  const h = String(hay == null ? '' : hay)
  if (!n) return true
  if (n.length > h.length) return false
  let i = 0
  for (let j = 0; j < h.length && i < n.length; j++) {
    if (h[j] === n[i]) i++
  }
  return i === n.length
}

/**
 * 首字母「有序匹配」（支持通配符）：needle 的每个字符需在 hay 中按顺序找到，
 * 其中 hay 里的 '*'（表外汉字占位）可以吃掉 needle 的任意一个字符。
 * 例：matchInitials('hqbzb', 'h*b*b') -> true
 *     matchInitials('swcxsys', 'swcx*fxsys') -> true
 */
function matchInitials(needle, hay) {
  const n = String(needle == null ? '' : needle)
  const h = String(hay == null ? '' : hay)
  if (!n) return true
  let i = 0
  for (let j = 0; j < h.length && i < n.length; j++) {
    if (h[j] === UNKNOWN || h[j] === n[i]) i++
  }
  return i === n.length
}

/**
 * 返回文本中未被字表收录的汉字（去重），用于补表 / 排查搜索不中的原因
 * 例：getUnknownChars('后勤保障部') -> ['勤', '障']
 */
function getUnknownChars(text) {
  const s = String(text == null ? '' : text)
  const out = []
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]
    if (isHanChar(ch.charCodeAt(0)) && !CHAR_MAP[ch] && out.indexOf(ch) < 0) out.push(ch)
  }
  return out
}

