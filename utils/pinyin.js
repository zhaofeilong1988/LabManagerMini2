// 构建 汉字 → 首字母 查询表（先写入者生效：主表 > 机构表 > 补充表）
const CHAR_MAP = {}
function addChars(letter, chars) {
  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i]
    if (ch && !CHAR_MAP[ch]) CHAR_MAP[ch] = letter
  }
}
